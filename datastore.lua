	local out = {}
	for i = 1, #self.entries do
		local h = self.entries[i].Handle
		if h then
			out[#out + 1] = h
		end
	end
	return out
end

function Claim:_bind(accessory, handle)
	for i = 1, #self.entries do
		if self.entries[i].Handle == handle then
			return self.entries[i]
		end
	end
	local key = keyOf(accessory, handle)
	local entry = nil
	for i = 1, #self.entries do
		local e = self.entries[i]
		if e.Key == key and (e.Handle == nil or not e.Handle:IsDescendantOf(Workspace)) then
			entry = e
			break
		end
	end
	if not entry then
		entry = newEntry(key)
		self.entries[#self.entries + 1] = entry
	end
	entry.Accessory = accessory
	entry.Handle = handle
	entry.Name = accessory.Name
	entry.State = "Attached"
	entry.LastPos = nil
	entry.GoneSince = nil
	self:_log("bind " .. entry.Name)
	return entry
end

-- Registers every accessory of `char` (and any that arrive later).
function Claim:Track(char)
	if self._charMaid then
		self._charMaid:Clean()
	end
	local maid = Util.Maid.new()
	self._charMaid = maid
	local function consider(inst)
		if inst:IsA("Accoutrement") then
			task.spawn(function()
				local handle = inst:WaitForChild("Handle", 10)
				if handle and handle:IsA("BasePart") and self.enabled then
					self:_bind(inst, handle)
				end
			end)
		end
	end
	for _, child in ipairs(char:GetChildren()) do
		consider(child)
	end
	maid:Give(char.ChildAdded:Connect(consider))
end

