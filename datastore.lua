function Proxy:Teleport(cf)
	self.Root.CFrame = cf
	self.Root.AssemblyLinearVelocity = Vector3.zero
	self.Root.AssemblyAngularVelocity = Vector3.zero
end

-- before physics: feed the humanoid its movement and jump
function Proxy:_control()
	local hum = self.Humanoid
	local input = self.input
	local cam = self.camera
	local yawCF = CFrame.Angles(0, cam.Yaw, 0)
	local dir = yawCF:VectorToWorldSpace(input.Move)
	local speed = self.walkSpeed
	if input.Sprint then
		speed = speed * self.cfg.SprintMul
	end
	if hum.WalkSpeed ~= speed then
		hum.WalkSpeed = speed
	end
	if hum.JumpPower ~= self.jumpPower then
		hum.JumpPower = self.jumpPower
	end
	if hum.HipHeight ~= self.hipHeight then
		hum.HipHeight = self.hipHeight
	end
	local lockedToCamera = cam.Shiftlock or cam.FirstPerson
	if hum.AutoRotate == lockedToCamera then
		hum.AutoRotate = not lockedToCamera
	end
	hum:Move(dir)
	hum.Jump = input.Jump
end

-- before each physics step: only the root collides while the humanoid is "running"
function Proxy:_collision()
	local light = LIGHT_STATES[self.Humanoid:GetState()] == true
	local parts = self.parts
	local root = self.Root
	for i = 1, #parts do
		local p = parts[i]
		local want = true
		if light then
			want = (p == root)
		end
		if p.CanCollide ~= want then
			p.CanCollide = want
		end
	end
end

-- after physics: void rescue, remember safe ground, face the camera when locked
function Proxy:_post()
	local root = self.Root
	local pos = root.Position
	if pos.Y < self.fpdh + 5 then
		root.CFrame = CFrame.new(self.lastSafe + Vector3.new(0, 5, 0)) * root.CFrame.Rotation
		root.AssemblyLinearVelocity = Vector3.new(0, 50, 0)
		root.AssemblyAngularVelocity = Vector3.zero
		return
	end
	local now = os.clock()
	if self.Humanoid:GetState() == HST.Running and now >= self._nextSafe then
		self._nextSafe = now + 0.25
		self.lastSafe = pos
	end
	local cam = self.camera
	if cam.Shiftlock or cam.FirstPerson then
		root.CFrame = CFrame.new(pos) * CFrame.Angles(0, cam.Yaw, 0)
	end
end

-- Heartbeat: publish position / velocity / simple state for everyone else
function Proxy:Step(dt)
	local root = self.Root
	self.Position = root.Position
	self.CF = root.CFrame
	local vel = root.AssemblyLinearVelocity
	self.Velocity = vel
	local flatSpeed = Vector3.new(vel.X, 0, vel.Z).Magnitude
	local st = self.Humanoid:GetState()
	local s = "fall"
	if st == HST.Running or st == HST.RunningNoPhysics or st == HST.Landed then
		if flatSpeed > 1 then
			s = "walk"
		else
			s = "idle"
		end
	elseif st == HST.Jumping then
		s = "jump"
	elseif st == HST.Freefall then
		if vel.Y > 0 then
			s = "jump"
		end
	elseif st == HST.Seated then
		s = "idle"
	end
	self.State = s
end

function Proxy:Destroy()
	self.maid:Clean()
end

return Proxy
end

__defs["body/virtual"] = function(require)
-- body/virtual.lua
-- Patchma-style kinematic body: no instances at all. Ground comes from one
-- downward raycast, gravity and jumping are integrated by hand (Yvel), and the
-- root rides at ground + 3 + HipHeight. Light and predictable, but it has no
-- horizontal collision (it walks through walls) - that is what the proxy is for.

local Players = game:GetService("Players")
local Workspace = game:GetService("Workspace")

local Virtual = {}
Virtual.__index = Virtual

-- deps = { input, camera, fpdh }
function Virtual.new(cfg, deps, startCF)
	local self = setmetatable({}, Virtual)
	self.cfg = cfg
	self.input = deps.input
	self.camera = deps.camera
	self.fpdh = deps.fpdh
	self.walkSpeed = cfg.WalkSpeed
	self.jumpPower = cfg.JumpPower
	self.hipHeight = cfg.HipHeight
	self.Position = startCF.Position
	self.Velocity = Vector3.zero
	self.State = "idle"
	self.yvel = 0
	self.onGround = false
	self.lastSafe = startCF.Position
	self._nextSafe = 0
	self._nextFilter = 0

	local look = startCF.LookVector
	local flat = Vector3.new(look.X, 0, look.Z)
	if flat.Magnitude < 0.001 then
		flat = Vector3.new(0, 0, -1)
	end
	self.facing = CFrame.lookAt(Vector3.zero, flat)
	self.CF = CFrame.new(self.Position) * self.facing

	local params = RaycastParams.new()
	params.FilterType = Enum.RaycastFilterType.Exclude
	params.RespectCanCollide = true
	params.IgnoreWater = true
	self.rayParams = params
	return self
end

function Virtual:SetWalkSpeed(n)
	self.walkSpeed = n
end

function Virtual:SetJumpPower(n)
	self.jumpPower = n
end

function Virtual:SetHipHeight(n)
	self.hipHeight = n
end

function Virtual:Teleport(cf)
	self.Position = cf.Position
	self.yvel = 0
	self.Velocity = Vector3.zero
	self.CF = CFrame.new(self.Position) * self.facing
end

function Virtual:_refreshFilter(now)
	if now < self._nextFilter then
		return
	end
	self._nextFilter = now + 0.5
	local list = {}
	for _, plr in ipairs(Players:GetPlayers()) do
		if plr.Character then
			list[#list + 1] = plr.Character
		end
	end
	self.rayParams.FilterDescendantsInstances = list
end

function Virtual:Step(dt)
	if dt <= 0 then
		return
	end
	local now = os.clock()
	self:_refreshFilter(now)
	local input = self.input
	local cam = self.camera

	-- horizontal motion, relative to the camera yaw
	local yawCF = CFrame.Angles(0, cam.Yaw, 0)
	local dir = yawCF:VectorToWorldSpace(input.Move)
	local speed = self.walkSpeed
	if input.Sprint then
		speed = speed * self.cfg.SprintMul
	end
	local pos = self.Position
	local oldPos = pos
	local hh = 3 + self.hipHeight

	-- ground probe
	local groundY = nil
	if pos.Y > self.fpdh then
		local hit = Workspace:Raycast(pos, Vector3.new(0, self.fpdh - pos.Y, 0), self.rayParams)
		if hit then
			groundY = hit.Position.Y
		end
	end

	-- vertical: stand, jump or fall
	local yvel = self.yvel
	local onGround = false
	if groundY and (pos.Y - groundY) < hh + 0.05 and yvel <= 0 then
		onGround = true
		yvel = 0
		local targetY = groundY + hh
		pos = Vector3.new(pos.X, pos.Y + (targetY - pos.Y) * math.min(dt * 20, 1), pos.Z)
		if input.Jump and self.jumpPower > 0 then
			yvel = self.jumpPower
			onGround = false
		end
	else
		yvel = yvel - Workspace.Gravity * dt
		if groundY and yvel <= 0 and pos.Y + yvel * dt < groundY + hh then
			-- would pass through the floor this frame: land on it
			pos = Vector3.new(pos.X, groundY + hh, pos.Z)
			yvel = 0
			onGround = true
		end
	end

	pos = pos + Vector3.new(dir.X * speed * dt, yvel * dt, dir.Z * speed * dt)

	-- fell out of the world: back to the last safe spot
	if pos.Y < self.fpdh + 5 then
		pos = self.lastSafe + Vector3.new(0, 5, 0)
		yvel = 0
	end
	if onGround and now >= self._nextSafe then
		self._nextSafe = now + 0.25
		self.lastSafe = pos
	end

	-- facing
	local flat = Vector3.new(dir.X, 0, dir.Z)
	if cam.Shiftlock or cam.FirstPerson then
		self.facing = yawCF
	elseif flat.Magnitude > 0.05 then
		self.facing = self.facing:Lerp(CFrame.lookAt(Vector3.zero, flat), math.min(dt * 12, 1))
	end

	local state = "fall"
	if onGround then
		if flat.Magnitude > 0.05 then
			state = "walk"
		else
			state = "idle"
		end
	elseif yvel > 0 then
		state = "jump"
	end

	self.yvel = yvel
	self.onGround = onGround
	self.State = state
	self.Position = pos
	self.CF = CFrame.new(pos) * self.facing
	self.Velocity = (pos - oldPos) / dt
end

function Virtual:Destroy()
end

return Virtual
end

__defs["claim/claim"] = function(require)
-- claim/claim.lua
-- Per-hat claim state machine, ownership metrics and reclaim logic.
--
-- Provider contract (Claim:SetProvider):
--   provider(entry, index, count, now) -> CFrame, Vector3
--   the CFrame the hat handle should be at, and the velocity of that target
--   point in studs/s (Vector3.zero is fine).
--
-- Entry states:
--   Attached  handle is still welded to something (cannot be claimed yet)
--   Unowned   detached, but someone else (or nobody) simulates it
--   Claiming  we own it; heavy phase + return-to-body burst
--   Owned     we own it; steady state
--   Blocked   anchored by someone else
--   Gone      handle destroyed / left workspace (kept so a respawn can re-bind)

local Util = require("core/util")
local Netless = require("claim/netless")

local Caps = Util.Caps
local Players = game:GetService("Players")
local Workspace = game:GetService("Workspace")

local Claim = {}
Claim.__index = Claim

----------------------------------------------------------------------
-- helpers
----------------------------------------------------------------------
local function meshInfo(handle)
	if handle:IsA("MeshPart") then
		return handle.MeshId, handle.TextureID
	end
	local sm = handle:FindFirstChildOfClass("SpecialMesh")
	if sm then
		return sm.MeshId, sm.TextureId
	end
	return "", ""
end

local function keyOf(accessory, handle)
	local mesh, tex = meshInfo(handle)
	return accessory.Name .. "|" .. tostring(mesh) .. "|" .. tostring(tex)
end

local function newEntry(key)
	return {
		Key = key,
		Name = "?",
		Handle = nil,
		Accessory = nil,
		State = "Gone",
		ClaimStart = 0,
		UnownedSince = nil,
		GoneSince = nil,
		WasOwned = false,
		LastPos = nil,
		LastCF = nil,
		Ema = nil,
		Drops = 0,
		Reowns = 0,
		ReownSum = 0,
		AltSign = 1,
		Capped = false,
	}
end

----------------------------------------------------------------------
-- construction
----------------------------------------------------------------------
function Claim.new(cfg, deps)
	local self = setmetatable({}, Claim)
	self.cfg = cfg.Claim
	self.physics = cfg.Physics
	self.deps = deps or {}
	self.player = Players.LocalPlayer
	self.entries = {}
	self.provider = nil
	self.enabled = true
	self.t0 = os.clock()
	self.log = {}
	self.events = Util.Signal.new()
	self.variant = self.cfg.Netless.Variant
	self.netlessFn = Netless.Variants[self.variant]
	if not self.netlessFn then
		self.variant = "patchma"
		self.netlessFn = Netless.Variants.patchma
	end
	self._ctx = { t = 0, dt = 0, age = 0 }
	self.stage2 = { entry = nil, frames = 0, cooldownUntil = 0 }
	self.stats = { drops = 0, reowns = 0, reownSum = 0, claims = 0, claimSum = 0, stage2 = 0, stage2ok = 0 }
	self.simMethod = "none"
	self._simWrite = nil
	self._charMaid = nil
	self._nanSet = false
	self._nextNan = 0

	-- ownership check: prefer ReceiveAge, fall back to the executor's isnetworkowner
	self.useReceiveAge = pcall(function()
		local probe = Instance.new("Part")
		local _ = probe.ReceiveAge
		probe:Destroy()
	end)

	-- void handling (read before we possibly set the height to NaN)
	local fpdh = Workspace.FallenPartsDestroyHeight
	self._fpdhOriginal = fpdh
	if fpdh ~= fpdh or fpdh == -math.huge then
		fpdh = -500
	end
	self.fpdh = fpdh
	if self.cfg.NaNDestroyHeight then
		pcall(function()
			Workspace.FallenPartsDestroyHeight = 0 / 0
		end)
		self._nanSet = true
	end

	self:_applyPhysicsSettings()
	self:_log("claim core ready (" .. Caps.summary() .. ")")
	return self
end

function Claim:_log(msg)
	local line = string.format("%6.1f %s", os.clock() - self.t0, msg)
	local log = self.log
	log[#log + 1] = line
	if #log > 40 then
		table.remove(log, 1)
	end
	self.events:Fire(line)
end

function Claim:_applyPhysicsSettings()
	if self.physics.DisableSleep then
		pcall(function()
			settings().Physics.AllowSleep = false
		end)
	end
	if self.physics.DisableThrottle then
		pcall(function()
			settings().Physics.PhysicsEnvironmentalThrottle = Enum.EnviromentalPhysicsThrottle.Disabled
		end)
	end
end

function Claim:_applySimRadius()
	local lp = self.player
	local radius = #Players:GetPlayers() * self.cfg.SimRadiusPerPlayer
	local write = self._simWrite
	if write == nil then
		if pcall(function()
			lp.SimulationRadius = radius
		end) then
			self.simMethod = "direct"
			write = function(v)
				lp.SimulationRadius = v
			end
		elseif Caps.sethiddenproperty and pcall(Caps.sethiddenproperty, lp, "SimulationRadius", radius) then
			self.simMethod = "hidden"
			write = function(v)
				Caps.sethiddenproperty(lp, "SimulationRadius", v)
			end
		elseif Caps.setsimulationradius and pcall(Caps.setsimulationradius, radius, radius) then
			self.simMethod = "setsimrad"
			write = function(v)
				Caps.setsimulationradius(v, v)
			end
		else
			self.simMethod = "none"
			write = false
		end
		self._simWrite = write
		if write then
			Caps.setHidden(lp, "MaximumSimulationRadius", radius)
		end
		self:_log("simulation radius via " .. self.simMethod)
	end
	if write then
		pcall(write, radius)
	end
end

