			l.LayoutOrder = i
			l.Text = ""
			l.Parent = rowsFrame
			rowLabels[i] = l
		end
		return l
	end

	local function refresh()
		local s = claim:Summary()
		summary.Text = string.format(
			"hats %d  owned %d  own%%(10s) %d%%  drops %d  reowns %d\nclaim avg %.2fs  reown avg %.2fs  stage2 %d (ok %d)  simrad: %s",
			s.hats, s.owned, math.floor(s.own * 100 + 0.5), s.drops, s.reowns,
			s.claimAvg, s.reownAvg, s.stage2, s.stage2ok, s.simMethod
		)

		local info = opts.getBodyInfo()
		bodyLabel.Text = string.format(
			"mode: %s   state: %s   physics: %s\nspeed %g  jump %g  hip %.1f  zoom %.1f%s",
			info.modeName, info.state, info.mode, info.walk, info.jump, info.hip, info.zoom, info.lock
		)

		local entries = claim.entries
		for i = 1, #entries do
			local e = entries[i]
			local row = getRow(i)
			row.Visible = true
			local avg = 0
			if e.Reowns > 0 then
				avg = e.ReownSum / e.Reowns
			end
			local pct = 0
			if e.Ema then
				pct = math.floor(e.Ema * 100 + 0.5)
			end
			local flag = ""
			if e.Capped then
				flag = " cap"
			end
			row.Text = string.format(
				"%-8s %-13s %-11s %3d%% d:%d r:%.2f%s",
				STATE_LABEL[e.State] or e.State, string.sub(e.Name, 1, 13), string.sub(e.BindLabel or "-", 1, 11),
				pct, e.Drops, avg, flag
			)
			row.TextColor3 = STATE_COLOR[e.State] or Color3.new(1, 1, 1)
		end
		for i = #entries + 1, #rowLabels do
			rowLabels[i].Visible = false
		end

		local lines = {}
		local log = claim.log
		for i = math.max(1, #log - 5), #log do
			lines[#lines + 1] = log[i]
		end
		logLabel.Text = table.concat(lines, "\n")

		for _, b in ipairs(buttons) do
			b.button.Text = b.get()
		end
	end

	task.spawn(function()
		while alive do
			local ok, err = pcall(refresh)
			if not ok then
				warn("[Exire] overlay refresh error: " .. tostring(err))
			end
			task.wait(0.2)
		end
	end)

	local function contains(p)
		local ap = root.AbsolutePosition
		local as = root.AbsoluteSize
		return p.X >= ap.X and p.Y >= ap.Y and p.X <= ap.X + as.X and p.Y <= ap.Y + as.Y
	end

	return { Gui = gui, Contains = contains }
end

return Overlay
end

__defs["hud/hud"] = function(require)
-- hud/hud.lua
-- Bottom-centre bar: the current mode's moves (with cooldown shading) above a
-- row of mode chips and music controls. Everything is clickable/tappable.
-- The toggle key (Config.Hud.ToggleKey) shows or hides it; the choice is saved.

local Util = require("core/util")
local Overlay = require("harness/overlay")

local UserInputService = game:GetService("UserInputService")

local Hud = {}
Hud.__index = Hud

local DEFAULT_COLOR = Color3.fromRGB(190, 190, 205)

local function keyLabel(key)
	if typeof(key) == "EnumItem" then
		return key.Name
	end
	return tostring(key)
end

local function newChip(parent, order, width)
	local b = Instance.new("TextButton")
	b.Name = Util.randomString()
	b.LayoutOrder = order
	b.Size = UDim2.new(0, width, 0, 30)
	b.BackgroundColor3 = Color3.fromRGB(20, 20, 30)
	b.BackgroundTransparency = 0.2
	b.BorderSizePixel = 0
	b.AutoButtonColor = true
	b.Font = Enum.Font.GothamMedium
	b.TextSize = 13
	b.TextColor3 = Color3.new(1, 1, 1)
	b.ZIndex = 2
	b.Text = ""
	b.Parent = parent
	local fill = Instance.new("Frame")
	fill.Name = "Fill"
	fill.BackgroundColor3 = Color3.new(0, 0, 0)
	fill.BackgroundTransparency = 0.4
	fill.BorderSizePixel = 0
	fill.AnchorPoint = Vector2.new(0, 1)
	fill.Position = UDim2.new(0, 0, 1, 0)
	fill.Size = UDim2.new(1, 0, 0, 0)
	fill.ZIndex = 3
	fill.Parent = b
	return b, fill
end

local function parseKey(name)
	local ok, kc = pcall(function()
		return Enum.KeyCode[name]
	end)
	if ok then
		return kc
	end
	return nil
end

-- cfg = Config.Hud, deps = { modes, music, saves }
function Hud.new(cfg, maid, deps)
	local self = setmetatable({}, Hud)
	self.modes = deps.modes
	self.music = deps.music
	self.saves = deps.saves
	self.moveChips = {}
	self.acc = 0

	local gui = Instance.new("ScreenGui")
	gui.Name = Util.randomString()
	gui.ResetOnSpawn = false
	gui.IgnoreGuiInset = true
	gui.DisplayOrder = 2147483646
	gui.Enabled = self.saves:Get("HudVisible", true) ~= false
	gui.Parent = Overlay.PickParent()
	maid:Give(gui)
	self.gui = gui

	local root = Instance.new("Frame")
	root.Name = Util.randomString()
	root.BackgroundTransparency = 1
	root.AnchorPoint = Vector2.new(0.5, 1)
	root.Position = UDim2.new(0.5, 0, 1, -14)
	root.AutomaticSize = Enum.AutomaticSize.XY
	root.Size = UDim2.new(0, 0, 0, 0)
	root.Parent = gui
	self.root = root

	local list = Instance.new("UIListLayout")
	list.SortOrder = Enum.SortOrder.LayoutOrder
	list.HorizontalAlignment = Enum.HorizontalAlignment.Center
	list.Padding = UDim.new(0, 6)
	list.Parent = root

	local function makeRow(order)
		local row = Instance.new("Frame")
		row.BackgroundTransparency = 1
		row.AutomaticSize = Enum.AutomaticSize.XY
		row.Size = UDim2.new(0, 0, 0, 30)
		row.LayoutOrder = order
		row.Parent = root
		local l = Instance.new("UIListLayout")
		l.FillDirection = Enum.FillDirection.Horizontal
		l.SortOrder = Enum.SortOrder.LayoutOrder
		l.Padding = UDim.new(0, 6)
		l.Parent = row
		return row
	end
	self.moveRow = makeRow(1)
	self.modeRow = makeRow(2)

	maid:Give(self.modes.ModeChanged:Connect(function()
		self:_rebuildModes()
		self:_rebuildMoves()
	end))
	maid:Give(self.modes.Registered:Connect(function()
		self:_rebuildModes()
	end))

	local toggleKey = parseKey(cfg.ToggleKey)
	maid:Give(UserInputService.InputBegan:Connect(function(input)
		if toggleKey and input.KeyCode == toggleKey and not UserInputService:GetFocusedTextBox() then
			gui.Enabled = not gui.Enabled
			self.saves:Set("HudVisible", gui.Enabled)
		end
	end))

	self:_rebuildModes()
	self:_rebuildMoves()
	return self
end

function Hud:_clear(row)
	for _, child in ipairs(row:GetChildren()) do
		if child:IsA("GuiButton") then
			child:Destroy()
		end
	end
end

function Hud:_rebuildModes()
	self:_clear(self.modeRow)
	local current = self.modes:GetCurrent()
	for i, m in ipairs(self.modes:List()) do
		local label = m.Name
		if m.Key then
			label = "[" .. keyLabel(m.Key) .. "] " .. label
		end
		local chip = newChip(self.modeRow, i, math.max(86, #label * 8 + 16))
		chip.Text = label
		local color = DEFAULT_COLOR
		if m.Meta and m.Meta.Color then
			color = m.Meta.Color
		end
		if current and current.Id == m.Id then
			chip.BackgroundColor3 = color
			chip.BackgroundTransparency = 0.1
			chip.TextColor3 = Color3.new(0, 0, 0)
		else
			chip.TextColor3 = color
		end
		chip.MouseButton1Click:Connect(function()
			self.modes:Set(m.Id, "hud")
		end)
	end

	local music = self.music
	local saves = self.saves
	local musicChip = newChip(self.modeRow, 100, 96)
	musicChip.TextColor3 = DEFAULT_COLOR
	musicChip.Text = music.muted and "music: off" or "music: on"
	musicChip.MouseButton1Click:Connect(function()
		music:SetMuted(not music.muted)
		saves:Set("Muted", music.muted)
		musicChip.Text = music.muted and "music: off" or "music: on"
	end)
	local function volumeChip(order, text, delta)
		local chip = newChip(self.modeRow, order, 34)
		chip.TextColor3 = DEFAULT_COLOR
		chip.Text = text
		chip.MouseButton1Click:Connect(function()
			music:SetVolume(math.floor((music.master + delta) * 10 + 0.5) / 10)
			saves:Set("Volume", music.master)
		end)
	end
	volumeChip(101, "-", -0.1)
	volumeChip(102, "+", 0.1)
end

function Hud:_rebuildMoves()
	self:_clear(self.moveRow)
	self.moveChips = {}
	for i, m in ipairs(self.modes:GetMoves()) do
		local chip, fill = newChip(self.moveRow, i, 120)
		chip.MouseButton1Click:Connect(function()
			self.modes:Trigger(m.Id)
		end)
		self.moveChips[i] = { chip = chip, fill = fill, id = m.Id, name = m.Name, key = m.Key }
	end
	self:_refreshMoves()
end

function Hud:_refreshMoves()
	for i, m in ipairs(self.modes:GetMoves()) do
		local c = self.moveChips[i]
		if c and c.id == m.Id then
			local frac = 0
			if m.Total > 0 then
				frac = math.clamp(m.Remaining / m.Total, 0, 1)
			end
			c.fill.Size = UDim2.new(1, 0, frac, 0)
			local label = c.name
			if c.key then
				label = "[" .. keyLabel(c.key) .. "] " .. label
			end
			if m.Remaining > 0.05 then
				label = label .. string.format(" %.1f", m.Remaining)
			end
			c.chip.Text = label
			if m.Active then
				c.chip.TextColor3 = Color3.fromRGB(255, 220, 120)
			else
				c.chip.TextColor3 = Color3.new(1, 1, 1)
			end
		end
	end
end

function Hud:Update(dt)
	self.acc = self.acc + dt
	if self.acc < 0.05 then
		return
	end
	self.acc = 0
	if self.gui.Enabled then
		self:_refreshMoves()
	end
end

function Hud.Contains(self, p)
	if not self.gui.Enabled then
		return false
	end
	local ap = self.root.AbsolutePosition
	local as = self.root.AbsoluteSize
	return p.X >= ap.X and p.Y >= ap.Y and p.X <= ap.X + as.X and p.Y <= ap.Y + as.Y
end

return Hud
end

__defs["init"] = function(require)
-- init.lua
-- Wires config, input, camera, body, skeleton, binder, modes, claim core,
-- start-up strategies and the test harness together.

local Util = require("core/util")
local Config = require("core/config")
local Claim = require("claim/claim")
local Start = require("claim/start")
local Netless = require("claim/netless")
local Input = require("body/input")
local CameraRig = require("body/camera")
local Body = require("body/body")
local Skeleton = require("skeleton/skeleton")
local Binder = require("skeleton/binder")
local Rigs = require("data/rigs")
local Registry = require("modes/registry")
local Builtin = require("modes/builtin")
local VFX = require("vfx/engine")
local Music = require("audio/music")
local Saves = require("core/saves")
local Hud = require("hud/hud")
local Driver = require("harness/driver")
local Overlay = require("harness/overlay")

local Players = game:GetService("Players")
local RunService = game:GetService("RunService")
local UserInputService = game:GetService("UserInputService")
local StarterGui = game:GetService("StarterGui")
local Workspace = game:GetService("Workspace")

local M = {}

function M.start(userCfg)
	local env = Util.getEnv()
	local previous = env.ExireReanimate
	if previous and type(previous.Stop) == "function" then
		pcall(previous.Stop)
	end

	local cfg = Config.build(userCfg)
	local maid = Util.Maid.new()
	local saves = Saves.new(cfg.Saves)
	local savedMode = saves:Get("Mode", nil)
	maid:Give(function()
		saves:Flush()
	end)
	local player = Players.LocalPlayer
	local running = true
	local api = {}
	local overlay = nil
	local hud = nil
	local body = nil

	local function keyOf(name)
		local ok, kc = pcall(function()
			return Enum.KeyCode[name]
		end)
		if ok then
			return kc
		end
		return nil
	end

	local function getRoot()
		local ch = player.Character
		if ch then
			return ch:FindFirstChild("HumanoidRootPart")
		end
		return nil
	end

	-- destroy height, read before the claim core may set it to NaN
	local fpdh = Workspace.FallenPartsDestroyHeight
	if fpdh ~= fpdh or fpdh == -math.huge then
		fpdh = -500
	end

	-- the body starts where the real character is standing
	local startCF = CFrame.new(0, 10, 0)
	local root = getRoot()
	if root then
		startCF = root.CFrame
	elseif Workspace.CurrentCamera then
		startCF = CFrame.new(Workspace.CurrentCamera.Focus.Position)
	end

	----------------------------------------------------------------
	-- input, camera, body
	----------------------------------------------------------------
	local input = Input.new(maid, {
		isOverGui = function(p)
			if overlay ~= nil and overlay.Gui.Enabled and overlay.Contains(p) then
				return true
			end
			return hud ~= nil and hud:Contains(p)
		end,
	})
	local camRig = CameraRig.new(cfg.Camera, maid, input, function()
		if body then
			return body:GetPosition()
		end
		return nil
	end)
	local savedZoom = saves:Get("Zoom", nil)
	if type(savedZoom) == "number" then
		camRig.Zoom = math.clamp(savedZoom, cfg.Camera.MinZoom, cfg.Camera.MaxZoom)
	end
	if cfg.Camera.ShiftLock and saves:Get("ShiftLock", nil) ~= nil then
		camRig.Shiftlock = saves:Get("ShiftLock", false) == true
	end
	body = Body.new(cfg.Body, { input = input, camera = camRig, fpdh = fpdh }, startCF)
	maid:Give(function()
		body:Destroy()
	end)

	----------------------------------------------------------------
	-- death effects: health bar + red hurt overlay
	----------------------------------------------------------------
	local healthWasOn = true
	pcall(function()
		healthWasOn = StarterGui:GetCoreGuiEnabled(Enum.CoreGuiType.Health)
	end)
	local function hideHealth()
		if cfg.HideDeathEffect then
			pcall(function()
				StarterGui:SetCoreGuiEnabled(Enum.CoreGuiType.Health, false)
			end)
		end
	end
	hideHealth()
	maid:Give(function()
		if cfg.HideDeathEffect and healthWasOn then
			pcall(function()
				StarterGui:SetCoreGuiEnabled(Enum.CoreGuiType.Health, true)
			end)
		end
	end)

	local hurt = nil
	local nextHurtSearch = 0
	local function hideHurtOverlay(now)
		if not cfg.HideDeathEffect then
			return
		end
		if hurt and hurt.Parent then
			if hurt.Visible then
				hurt.Visible = false
			end
			return
		end
		if now >= nextHurtSearch then
			nextHurtSearch = now + 1
			pcall(function()
				hurt = game:GetService("CoreGui").TopBarApp.TopBarApp.FullScreenFrame.HurtOverlay
			end)
		end
	end

	-- the real (dead) body must never push the proxy around
	local function ghostReal()
		local ch = player.Character
		if not ch then
			return
		end
		for _, v in ipairs(ch:GetChildren()) do
			if v:IsA("BasePart") and v.CanCollide then
				v.CanCollide = false
			end
		end
	end

	----------------------------------------------------------------
	-- claim core + formations
	----------------------------------------------------------------
	local claim = Claim.new(cfg, {
		getRoot = getRoot,
		getBodyPos = function()
			local r = getRoot()
			if r then
				return r.Position
			end
			return body:GetPosition()
		end,
		getFollowCF = function()
			return CFrame.new(body:GetPosition())
		end,
		getLTM = function()
			return camRig.LTM
		end,
	})
	local driver = Driver.new(cfg.Harness, body)

	----------------------------------------------------------------
	-- skeleton, binder, modes
	----------------------------------------------------------------
	local skeleton = Skeleton.new()
	local binder = Binder.new(cfg.Binder, skeleton, Rigs)
	local vfx = VFX.new(cfg.VFX, maid)
	local music = Music.new(cfg.Music, maid)
	music:SetVolume(saves:Get("Volume", cfg.Music.Volume))
	music:SetMuted(saves:Get("Muted", false) == true)
	local modes = Registry.new(cfg.Modes, maid, {
		body = body,
		skeleton = skeleton,
		getSlot = function(name)
			return binder:GetSlot(name)
		end,
		base = cfg.Body,
		vfx = vfx,
		onRegister = function(mode)
			for slotName, def in pairs(mode.Slots) do
				binder:DeclareSlot(slotName, def)
			end
			binder:Reresolve()
		end,
	})
	maid:Give(modes.ModeChanged:Connect(function(new, old, reason)
		local from = "-"
		if old then
			from = old.Name
		end
		claim:_log("mode " .. from .. " -> " .. new.Name .. " (" .. reason .. ")")
		if new.Music == false then
			music:Stop()
		elseif new.Music ~= nil then
			music:Play(new.Music)
		end
		saves:Set("Mode", new.Id)
	end))
	if cfg.Modes.LoadBuiltin then
		Builtin.register(modes)
	end
	if type(cfg.Modes.Register) == "function" then
		local ok, err = pcall(cfg.Modes.Register, modes)
		if not ok then
			warn("[Exire] Modes.Register failed: " .. tostring(err))
		end
	end
	modes:Start()
	if cfg.Saves.RestoreMode and type(savedMode) == "string" and modes.modes[savedMode] and modes.modes[savedMode] ~= modes.current then
		modes:Set(savedMode, "save")
	end
	if cfg.Hud.Enabled then
		hud = Hud.new(cfg.Hud, maid, { modes = modes, music = music, saves = saves })
	end

	-- who tells the claim system where each hat goes
	local targets = cfg.Targets
	local formationProvider = driver:GetProvider()
	local function rigProvider(entry, index, count, now)
		local b = entry.Binding
		if not b then
			return nil
		end
		return b.Part.CF, body:GetVelocity()
	end
	local function applyTargets()
		if targets == "formation" then
			claim:SetProvider(formationProvider)
		else
			claim:SetProvider(rigProvider)
		end
	end
	applyTargets()

	----------------------------------------------------------------
	-- character bring-up (initial character and every respawn)
	----------------------------------------------------------------
	local token = 0
	local function bringUp(char)
		if not char then
			return
		end
		token = token + 1
		local myToken = token
		hideHealth()
		task.spawn(function()
			local hum = char:WaitForChild("Humanoid", 10)
			if not hum then
				return
			end
			if cfg.Start.ScanDelay > 0 then
				task.wait(cfg.Start.ScanDelay)
			end
			if not running or myToken ~= token then
				return
			end
			claim:Track(char)
			-- wait (frame by frame) until the accessory list has settled
			local t0 = os.clock()
			local stable = 0
			local last = -1
			while os.clock() - t0 < cfg.Start.SettleMax do
				local n = #claim:GetHandles()
				if n > 0 and n == last then
					stable = stable + 1
				else
					stable = 0
				end
				last = n
				if stable >= 2 and os.clock() - t0 >= cfg.Start.SettleMin then
					break
				end
				task.wait()
			end
			if not running or myToken ~= token then
				return
			end
			local startCtx = {
				char = char,
				cfg = cfg.Start,
				getHandles = function()
					return claim:GetHandles()
				end,
				log = function(msg)
					claim:_log(msg)
				end,
				isAlive = function()
					return running and myToken == token and char.Parent ~= nil
				end,
			}
			Start.run(startCtx)

			-- accessories that arrive after the kill are welded to the dead head: free them too
			local sweepUntil = os.clock() + 2
			while os.clock() < sweepUntil and startCtx.isAlive() do
				task.wait(0.15)
				if claim:CountState("Attached") > 0 then
					claim:_log("late hat found, freeing again")
					Start.run(startCtx)
				end
			end
		end)
	end

	maid:Give(player.CharacterAdded:Connect(function(char)
		if cfg.Start.AutoRestartOnRespawn then
			bringUp(char)
		end
	end))
	if cfg.Start.AutoRun and player.Character then
		bringUp(player.Character)
	end

	----------------------------------------------------------------
	-- frame loops
	----------------------------------------------------------------
	local renderName = "Exire_" .. Util.randomString()
	RunService:BindToRenderStep(renderName, Enum.RenderPriority.Camera.Value + 1, function(dt)
		camRig:Update(dt)
		hideHurtOverlay(os.clock())
	end)
	maid:Give(function()
		RunService:UnbindFromRenderStep(renderName)
	end)
	maid:Give(RunService.Heartbeat:Connect(function(dt)
		body:Step(dt)
		skeleton:SetRoot(body:GetCF())
		binder:Step(claim.entries)
		modes:Update(dt)
		skeleton:Refresh()
		vfx:Update(dt)
		music:Update(dt)
		if hud then
			hud:Update(dt)
		end
		saves:Set("Zoom", math.floor(camRig.Zoom * 10 + 0.5) / 10)
		saves:Set("ShiftLock", camRig.Shiftlock == true)
		saves:Step(dt)
		ghostReal()
		claim:Step(dt)
	end))

	----------------------------------------------------------------
	-- overlay actions
	----------------------------------------------------------------
	local function onOff(v)
		if v then
			return "on"
		end
		return "off"
	end

	local actions = {
		{
			text = function()
				return "physics: " .. body.mode
			end,
			run = function()
				body:SetMode(Util.cycle(Body.Modes, body.mode))
			end,
		},
		{
			text = function()
				local cur = modes:GetCurrent()
				if cur then
					return "mode: " .. cur.Name .. " (next)"
				end
				return "mode: -"
			end,
			run = function()
				modes:Next("api")
			end,
		},
		{
			text = function()
				return "default mode: " .. onOff(cfg.Modes.DefaultMode.Enabled)
			end,
			run = function()
				cfg.Modes.DefaultMode.Enabled = not cfg.Modes.DefaultMode.Enabled
			end,
		},
		{
			text = function()
				return "hat targets: " .. targets
			end,
			run = function()
				if targets == "rig" then
					targets = "formation"
				else
					targets = "rig"
				end
				applyTargets()
			end,
		},
		{
			text = function()
				return "netless: " .. claim.variant
			end,
			run = function()
				claim:SetVariant(Netless.nextName(claim.variant))
			end,
		},
		{
			text = function()
				return "formation: " .. driver.formationName
			end,
			run = function()
				driver:CycleFormation()
			end,
		},
		{
			text = function()
				return "heavy phase: " .. tostring(claim.cfg.HeavyPhase) .. "s"
			end,
			run = function()
