function Claim:_isOwner(part)
	if self.useReceiveAge and self.cfg.OwnerCheck ~= "isnetworkowner" then
		return part.ReceiveAge == 0
	end
	if Caps.isnetworkowner then
		local ok, r = pcall(Caps.isnetworkowner, part)
		if ok then
			return r == true
		end
	end
	local ok, age = pcall(function()
		return part.ReceiveAge
	end)
	return ok and age == 0
end

