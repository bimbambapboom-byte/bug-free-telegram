----------------------------------------------------------------------
-- Maid: collect things to clean up with one call
----------------------------------------------------------------------
local Maid = {}
Maid.__index = Maid

function Maid.new()
	return setmetatable({ _items = {} }, Maid)
end

function Maid:Give(item)
	if item ~= nil then
		self._items[#self._items + 1] = item
	end
	return item
end

local function cleanItem(item)
	local kind = typeof(item)
	if kind == "RBXScriptConnection" then
		item:Disconnect()
	elseif kind == "Instance" then
		item:Destroy()
	elseif kind == "function" then
		item()
	elseif kind == "thread" then
		task.cancel(item)
	elseif kind == "table" then
		if type(item.Disconnect) == "function" then
			item:Disconnect()
		elseif type(item.Destroy) == "function" then
			item:Destroy()
		elseif type(item.Clean) == "function" then
			item:Clean()
		end
	end
end

function Maid:Clean()
	local items = self._items
	self._items = {}
	for i = #items, 1, -1 do
		local ok, err = pcall(cleanItem, items[i])
		if not ok then
			warn("[Exire] cleanup error: " .. tostring(err))
		end
	end
end

Maid.Destroy = Maid.Clean
Util.Maid = Maid

----------------------------------------------------------------------
-- Signal: tiny synchronous event
----------------------------------------------------------------------
local Signal = {}
Signal.__index = Signal

function Signal.new()
	return setmetatable({ _list = {} }, Signal)
end

function Signal:Connect(fn)
	local list = self._list
	local conn = { Connected = true, Fn = fn }
	function conn.Disconnect(c)
		if not c.Connected then
			return
		end
		c.Connected = false
		for i = 1, #list do
			if list[i] == c then
				table.remove(list, i)
				break
			end
		end
	end
	list[#list + 1] = conn
	return conn
end

function Signal:Fire(...)
	local snapshot = table.clone(self._list)
	for i = 1, #snapshot do
		local conn = snapshot[i]
		if conn.Connected then
			local ok, err = pcall(conn.Fn, ...)
			if not ok then
				warn("[Exire] signal handler error: " .. tostring(err))
			end
		end
	end
end

function Signal:DisconnectAll()
	local snapshot = table.clone(self._list)
	for i = 1, #snapshot do
		snapshot[i]:Disconnect()
	end
end

Util.Signal = Signal

return Util
end

__defs["harness/driver"] = function(require)
-- harness/driver.lua
-- Formations: give every hat a target relative to the body so the claim system
-- can be measured on its own. The body itself (movement, jumping, falling) now
-- lives in body/; this file only turns "where the body is" into hat targets.

local Util = require("core/util")

local Players = game:GetService("Players")
local Workspace = game:GetService("Workspace")

local Driver = {}
Driver.__index = Driver

----------------------------------------------------------------------
-- formations: fn(index, count, t) -> offset (Vector3), yaw (radians)
----------------------------------------------------------------------
local Formations = {}
Formations.Order = { "ring", "vertical", "line", "spiral", "static" }
Formations.Fns = {}

Formations.Fns.ring = function(i, n, t)
	local a = (i / math.max(n, 1)) * math.pi * 2 + t * 0.6
	return Vector3.new(math.cos(a) * 6, 1, math.sin(a) * 6), -a
end

Formations.Fns.vertical = function(i, n, t)
	local a = (i / math.max(n, 1)) * math.pi * 2 + t * 0.9
	return Vector3.new(math.cos(a) * 5, 6 + math.sin(a) * 5, 0), 0
end

Formations.Fns.line = function(i, n, t)
	return Vector3.new((i - (n + 1) / 2) * 3, 3, 0), 0
end

Formations.Fns.spiral = function(i, n, t)
	local a = i * 0.8 + t * 2
	local r = 3 + i * 0.7
	return Vector3.new(math.cos(a) * r, 2 + math.sin(t * 2 + i) * 2, math.sin(a) * r), -a
end

Formations.Fns.static = function(i, n, t)
	return Vector3.new((i - (n + 1) / 2) * 2.5, 4, -3), 0
end

----------------------------------------------------------------------
-- driver
----------------------------------------------------------------------
function Driver.new(cfg, body)
	local self = setmetatable({}, Driver)
	self.cfg = cfg
	self.body = body
	self.formationName = cfg.Formation
	if not Formations.Fns[self.formationName] then
		self.formationName = "ring"
	end
	return self
end

function Driver:CycleFormation()
	self.formationName = Util.cycle(Formations.Order, self.formationName)
end

-- jump the body forward (flat, camera-relative) and drop it onto the ground there
function Driver:Teleport(distance)
	local look = Vector3.new(0, 0, -1)
	local cam = Workspace.CurrentCamera
	if cam then
		local l = cam.CFrame.LookVector
		local flat = Vector3.new(l.X, 0, l.Z)
		if flat.Magnitude > 0.001 then
			look = flat.Unit
		end
	end
	local target = self.body:GetPosition() + look * distance

	local characters = {}
	for _, plr in ipairs(Players:GetPlayers()) do
		if plr.Character then
			characters[#characters + 1] = plr.Character
		end
	end
	local params = RaycastParams.new()
	params.FilterType = Enum.RaycastFilterType.Exclude
	params.FilterDescendantsInstances = characters
	local hit = Workspace:Raycast(target + Vector3.new(0, 200, 0), Vector3.new(0, -400, 0), params)
	if hit then
		target = hit.Position + Vector3.new(0, 4, 0)
	end
	self.body:Teleport(CFrame.new(target))
end

-- provider for the claim system: formation slot -> target CFrame + velocity
function Driver:GetProvider()
	return function(entry, index, count, now)
		local fn = Formations.Fns[self.formationName]
		local offset, yaw = fn(index, count, now)
		local base = CFrame.new(self.body:GetPosition())
		return base * CFrame.new(offset) * CFrame.Angles(0, yaw, 0), self.body:GetVelocity()
	end
end

return Driver
end

__defs["harness/overlay"] = function(require)
-- harness/overlay.lua
-- On-screen claim monitor + test buttons (works with mouse and touch).

local Util = require("core/util")

local Players = game:GetService("Players")

local Caps = Util.Caps

local Overlay = {}

local STATE_LABEL = {
	Attached = "WELDED",
	Unowned = "UNOWNED",
	Claiming = "CLAIMING",
	Owned = "OWNED",
	Gone = "GONE",
	Blocked = "ANCHORED",
}

local STATE_COLOR = {
	Attached = Color3.fromRGB(160, 160, 170),
	Unowned = Color3.fromRGB(255, 110, 110),
	Claiming = Color3.fromRGB(255, 220, 110),
	Owned = Color3.fromRGB(120, 255, 150),
	Gone = Color3.fromRGB(120, 120, 130),
	Blocked = Color3.fromRGB(255, 170, 90),
}

local function pickParent()
	if Caps.gethui then
		local ok, ui = pcall(Caps.gethui)
		if ok and ui then
			return ui
		end
	end
	local ok, core = pcall(function()
		return game:GetService("CoreGui")
	end)
	if ok and core then
		local writable = pcall(function()
			local f = Instance.new("Folder")
			f.Parent = core
			f:Destroy()
		end)
		if writable then
			return core
		end
	end
	return Players.LocalPlayer:WaitForChild("PlayerGui")
end

-- opts = { maid, claim, actions = { { text = fn, run = fn }, ... }, version, getBodyInfo = fn }
function Overlay.new(opts)
	local maid = opts.maid
	local claim = opts.claim
	local alive = true
	maid:Give(function()
		alive = false
	end)

	local gui = Instance.new("ScreenGui")
	gui.Name = Util.randomString()
	gui.ResetOnSpawn = false
	gui.IgnoreGuiInset = true
	gui.DisplayOrder = 2147483647
	gui.Parent = pickParent()
	maid:Give(gui)

	local root = Instance.new("Frame")
	root.Name = Util.randomString()
	root.AutomaticSize = Enum.AutomaticSize.Y
	root.Size = UDim2.new(0, 430, 0, 0)
	root.Position = UDim2.new(0, 8, 0, 8)
	root.BackgroundColor3 = Color3.fromRGB(10, 10, 16)
	root.BackgroundTransparency = 0.15
	root.BorderSizePixel = 0
	root.Parent = gui

	local pad = Instance.new("UIPadding")
	pad.PaddingTop = UDim.new(0, 6)
	pad.PaddingBottom = UDim.new(0, 6)
	pad.PaddingLeft = UDim.new(0, 6)
	pad.PaddingRight = UDim.new(0, 6)
	pad.Parent = root

	local layout = Instance.new("UIListLayout")
	layout.SortOrder = Enum.SortOrder.LayoutOrder
	layout.Padding = UDim.new(0, 2)
	layout.Parent = root

	local function makeLabel(order, height, size)
		local l = Instance.new("TextLabel")
		l.BackgroundTransparency = 1
		l.Size = UDim2.new(1, 0, 0, height)
		l.Font = Enum.Font.Code
		l.TextSize = size
		l.TextXAlignment = Enum.TextXAlignment.Left
		l.TextYAlignment = Enum.TextYAlignment.Top
		l.TextColor3 = Color3.fromRGB(225, 225, 235)
		l.LayoutOrder = order
		l.Text = ""
		l.Parent = root
		return l
	end

	local header = makeLabel(1, 16, 14)
	header.Text = "Exire Reanimate " .. tostring(opts.version) .. "  |  claim harness"
	header.TextColor3 = Color3.fromRGB(190, 160, 255)

	local capsLabel = makeLabel(2, 14, 11)
	capsLabel.Text = Caps.summary()
	capsLabel.TextColor3 = Color3.fromRGB(150, 150, 165)

	local summary = makeLabel(3, 30, 12)
	local bodyLabel = makeLabel(4, 30, 12)
	bodyLabel.TextColor3 = Color3.fromRGB(170, 215, 255)

	local rowsFrame = Instance.new("Frame")
	rowsFrame.BackgroundTransparency = 1
	rowsFrame.AutomaticSize = Enum.AutomaticSize.Y
	rowsFrame.Size = UDim2.new(1, 0, 0, 0)
	rowsFrame.LayoutOrder = 5
	rowsFrame.Parent = root
	local rowsLayout = Instance.new("UIListLayout")
	rowsLayout.SortOrder = Enum.SortOrder.LayoutOrder
	rowsLayout.Parent = rowsFrame
	local rowLabels = {}

	local logLabel = makeLabel(6, 84, 11)
	logLabel.TextColor3 = Color3.fromRGB(170, 170, 185)

	local buttonsFrame = Instance.new("Frame")
	buttonsFrame.BackgroundTransparency = 1
	buttonsFrame.AutomaticSize = Enum.AutomaticSize.Y
	buttonsFrame.Size = UDim2.new(1, 0, 0, 0)
	buttonsFrame.LayoutOrder = 7
	buttonsFrame.Parent = root
	local grid = Instance.new("UIGridLayout")
	grid.CellSize = UDim2.new(0.5, -3, 0, 24)
	grid.CellPadding = UDim2.new(0, 6, 0, 4)
	grid.SortOrder = Enum.SortOrder.LayoutOrder
	grid.Parent = buttonsFrame

	local buttons = {}
	for i, action in ipairs(opts.actions) do
		local b = Instance.new("TextButton")
		b.LayoutOrder = i
		b.BackgroundColor3 = Color3.fromRGB(38, 38, 52)
		b.BorderSizePixel = 0
		b.TextColor3 = Color3.new(1, 1, 1)
		b.Font = Enum.Font.Code
		b.TextSize = 12
		b.AutoButtonColor = true
		b.Text = action.text()
		b.Parent = buttonsFrame
		maid:Give(b.MouseButton1Click:Connect(function()
			action.run()
			b.Text = action.text()
		end))
		buttons[#buttons + 1] = { button = b, get = action.text }
	end

	local function getRow(i)
		local l = rowLabels[i]
		if not l then
			l = Instance.new("TextLabel")
			l.BackgroundTransparency = 1
			l.Size = UDim2.new(1, 0, 0, 15)
			l.Font = Enum.Font.Code
			l.TextSize = 12
			l.TextXAlignment = Enum.TextXAlignment.Left
			l.LayoutOrder = i
			l.Text = ""
			l.Parent = rowsFrame
			rowLabels[i] = l
		end
		return l
	end

	local function refresh()
		local s = claim:Summary()
		summary.Text = string.format(
			"hats %d  owned %d  own%%(10s) %d%%  drops %d  reowns %d\nclaim avg %.2fs  reown avg %.2fs  stage2 %d (ok %d)  simrad: %s",
			s.hats, s.owned, math.floor(s.own * 100 + 0.5), s.drops, s.reowns,
			s.claimAvg, s.reownAvg, s.stage2, s.stage2ok, s.simMethod
		)

		local info = opts.getBodyInfo()
		bodyLabel.Text = string.format(
			"body: %s  state: %s  speed %g  jump %g  hip %g\ncamera zoom %.1f%s",
			info.mode, info.state, info.walk, info.jump, info.hip, info.zoom, info.lock
		)

		local entries = claim.entries
		for i = 1, #entries do
			local e = entries[i]
			local row = getRow(i)
			row.Visible = true
			local avg = 0
			if e.Reowns > 0 then
				avg = e.ReownSum / e.Reowns
			end
			local pct = 0
			if e.Ema then
				pct = math.floor(e.Ema * 100 + 0.5)
			end
			local flag = ""
			if e.Capped then
				flag = " cap"
			end
			row.Text = string.format(
				"%-9s %-16s %3d%% drops:%d reown:%.2fs%s",
				STATE_LABEL[e.State] or e.State, string.sub(e.Name, 1, 16), pct, e.Drops, avg, flag
			)
			row.TextColor3 = STATE_COLOR[e.State] or Color3.new(1, 1, 1)
		end
		for i = #entries + 1, #rowLabels do
			rowLabels[i].Visible = false
		end

		local lines = {}
		local log = claim.log
		for i = math.max(1, #log - 5), #log do
			lines[#lines + 1] = log[i]
		end
		logLabel.Text = table.concat(lines, "\n")

		for _, b in ipairs(buttons) do
			b.button.Text = b.get()
		end
	end

	task.spawn(function()
		while alive do
			local ok, err = pcall(refresh)
			if not ok then
				warn("[Exire] overlay refresh error: " .. tostring(err))
			end
			task.wait(0.2)
		end
	end)

	local function contains(p)
		local ap = root.AbsolutePosition
		local as = root.AbsoluteSize
		return p.X >= ap.X and p.Y >= ap.Y and p.X <= ap.X + as.X and p.Y <= ap.Y + as.Y
	end

	return { Gui = gui, Contains = contains }
end

return Overlay
end

__defs["init"] = function(require)
-- init.lua
-- Wires config, input, camera, body, claim core, start-up strategies and the
-- test harness together.

local Util = require("core/util")
local Config = require("core/config")
local Claim = require("claim/claim")
local Start = require("claim/start")
local Netless = require("claim/netless")
local Input = require("body/input")
local CameraRig = require("body/camera")
local Body = require("body/body")
local Driver = require("harness/driver")
local Overlay = require("harness/overlay")

local Players = game:GetService("Players")
local RunService = game:GetService("RunService")
local StarterGui = game:GetService("StarterGui")
local Workspace = game:GetService("Workspace")

local M = {}

function M.start(userCfg)
	local env = Util.getEnv()
	local previous = env.ExireReanimate
	if previous and type(previous.Stop) == "function" then
		pcall(previous.Stop)
	end

	local cfg = Config.build(userCfg)
	local maid = Util.Maid.new()
	local player = Players.LocalPlayer
	local running = true
	local api = {}
	local overlay = nil
	local body = nil

	local function getRoot()
		local ch = player.Character
		if ch then
			return ch:FindFirstChild("HumanoidRootPart")
		end
		return nil
	end

	-- destroy height, read before the claim core may set it to NaN
	local fpdh = Workspace.FallenPartsDestroyHeight
	if fpdh ~= fpdh or fpdh == -math.huge then
		fpdh = -500
	end

	-- the body starts where the real character is standing
	local startCF = CFrame.new(0, 10, 0)
	local root = getRoot()
	if root then
		startCF = root.CFrame
	elseif Workspace.CurrentCamera then
		startCF = CFrame.new(Workspace.CurrentCamera.Focus.Position)
	end

	----------------------------------------------------------------
	-- input, camera, body
	----------------------------------------------------------------
	local input = Input.new(maid, {
		isOverGui = function(p)
			return overlay ~= nil and overlay.Contains(p)
		end,
	})
	local camRig = CameraRig.new(cfg.Camera, maid, input, function()
		if body then
			return body:GetPosition()
		end
		return nil
	end)
	body = Body.new(cfg.Body, { input = input, camera = camRig, fpdh = fpdh }, startCF)
	maid:Give(function()
		body:Destroy()
	end)

	----------------------------------------------------------------
	-- death effects: health bar + red hurt overlay
	----------------------------------------------------------------
	local healthWasOn = true
	pcall(function()
		healthWasOn = StarterGui:GetCoreGuiEnabled(Enum.CoreGuiType.Health)
	end)
	local function hideHealth()
		if cfg.HideDeathEffect then
			pcall(function()
				StarterGui:SetCoreGuiEnabled(Enum.CoreGuiType.Health, false)
			end)
		end
	end
	hideHealth()
	maid:Give(function()
		if cfg.HideDeathEffect and healthWasOn then
			pcall(function()
				StarterGui:SetCoreGuiEnabled(Enum.CoreGuiType.Health, true)
			end)
		end
	end)

	local hurt = nil
	local nextHurtSearch = 0
	local function hideHurtOverlay(now)
		if not cfg.HideDeathEffect then
			return
		end
		if hurt and hurt.Parent then
			if hurt.Visible then
				hurt.Visible = false
			end
			return
		end
		if now >= nextHurtSearch then
			nextHurtSearch = now + 1
			pcall(function()
				hurt = game:GetService("CoreGui").TopBarApp.TopBarApp.FullScreenFrame.HurtOverlay
			end)
		end
	end

	-- the real (dead) body must never push the proxy around
	local function ghostReal()
		local ch = player.Character
		if not ch then
			return
		end
		for _, v in ipairs(ch:GetChildren()) do
			if v:IsA("BasePart") and v.CanCollide then
				v.CanCollide = false
			end
		end
	end

	----------------------------------------------------------------
	-- claim core + formations
	----------------------------------------------------------------
	local claim = Claim.new(cfg, {
		getRoot = getRoot,
		getBodyPos = function()
			local r = getRoot()
			if r then
				return r.Position
			end
			return body:GetPosition()
		end,
		getFollowCF = function()
			return CFrame.new(body:GetPosition())
		end,
		getLTM = function()
			return camRig.LTM
		end,
	})
	local driver = Driver.new(cfg.Harness, body)
	claim:SetProvider(driver:GetProvider())

	----------------------------------------------------------------
	-- character bring-up (initial character and every respawn)
	----------------------------------------------------------------
	local token = 0
	local function bringUp(char)
		if not char then
			return
		end
		token = token + 1
		local myToken = token
		hideHealth()
		task.spawn(function()
			local hum = char:WaitForChild("Humanoid", 10)
			if not hum then
				return
			end
			if cfg.Start.ScanDelay > 0 then
				task.wait(cfg.Start.ScanDelay)
			end
			if not running or myToken ~= token then
				return
			end
			claim:Track(char)
			-- wait (frame by frame) until the accessory list has settled
			local t0 = os.clock()
			local stable = 0
			local last = -1
			while os.clock() - t0 < cfg.Start.SettleMax do
				local n = #claim:GetHandles()
				if n > 0 and n == last then
					stable = stable + 1
				else
					stable = 0
				end
				last = n
				if stable >= 2 and os.clock() - t0 >= cfg.Start.SettleMin then
					break
				end
				task.wait()
			end
			if not running or myToken ~= token then
				return
			end
			local startCtx = {
				char = char,
				cfg = cfg.Start,
				getHandles = function()
					return claim:GetHandles()
				end,
				log = function(msg)
					claim:_log(msg)
				end,
				isAlive = function()
					return running and myToken == token and char.Parent ~= nil
				end,
			}
			Start.run(startCtx)

			-- accessories that arrive after the kill are welded to the dead head: free them too
			local sweepUntil = os.clock() + 2
			while os.clock() < sweepUntil and startCtx.isAlive() do
				task.wait(0.15)
				if claim:CountState("Attached") > 0 then
					claim:_log("late hat found, freeing again")
					Start.run(startCtx)
				end
			end
		end)
	end

	maid:Give(player.CharacterAdded:Connect(function(char)
		if cfg.Start.AutoRestartOnRespawn then
			bringUp(char)
		end
	end))
	if cfg.Start.AutoRun and player.Character then
		bringUp(player.Character)
	end

	----------------------------------------------------------------
	-- frame loops
	----------------------------------------------------------------
	local renderName = "Exire_" .. Util.randomString()
	RunService:BindToRenderStep(renderName, Enum.RenderPriority.Camera.Value + 1, function(dt)
		camRig:Update(dt)
		hideHurtOverlay(os.clock())
	end)
	maid:Give(function()
		RunService:UnbindFromRenderStep(renderName)
	end)
	maid:Give(RunService.Heartbeat:Connect(function(dt)
		body:Step(dt)
		ghostReal()
		claim:Step(dt)
	end))

	----------------------------------------------------------------
	-- overlay actions
	----------------------------------------------------------------
	local function onOff(v)
		if v then
			return "on"
		end
		return "off"
	end

	local actions = {
		{
			text = function()
				return "physics: " .. body.mode
			end,
			run = function()
				body:SetMode(Util.cycle(Body.Modes, body.mode))
			end,
		},
		{
			text = function()
				return "walkspeed: " .. tostring(body.walkSpeed)
			end,
			run = function()
				body:SetWalkSpeed(Util.cycle({ 16, 30, 60, 100 }, body.walkSpeed))
			end,
		},
		{
			text = function()
				return "jump power: " .. tostring(body.jumpPower)
			end,
			run = function()
				body:SetJumpPower(Util.cycle({ 50, 80, 120 }, body.jumpPower))
			end,
		},
		{
			text = function()
				return "hip height: " .. tostring(body.hipHeight)
			end,
			run = function()
				body:SetHipHeight(Util.cycle({ 0, 4, 10 }, body.hipHeight))
			end,
		},
		{
			text = function()
				return "netless: " .. claim.variant
			end,
			run = function()
				claim:SetVariant(Netless.nextName(claim.variant))
			end,
		},
		{
			text = function()
				return "formation: " .. driver.formationName
			end,
			run = function()
				driver:CycleFormation()
			end,
		},
		{
			text = function()
				return "heavy phase: " .. tostring(claim.cfg.HeavyPhase) .. "s"
			end,
			run = function()
				claim.cfg.HeavyPhase = Util.cycle({ 0, 2, 5.67 }, claim.cfg.HeavyPhase)
			end,
		},
		{
			text = function()
				return "burst: " .. claim.cfg.BurstMode
			end,
			run = function()
				claim.cfg.BurstMode = Util.cycle({ "ballistic", "up", "none" }, claim.cfg.BurstMode)
			end,
		},
		{
			text = function()
				return "reclaim stage2: " .. onOff(claim.cfg.Reclaim.Stage2)
			end,
			run = function()
				claim.cfg.Reclaim.Stage2 = not claim.cfg.Reclaim.Stage2
			end,
		},
		{
			text = function()
				return "body follow: " .. onOff(claim.cfg.Reclaim.BodyFollow)
			end,
			run = function()
				claim.cfg.Reclaim.BodyFollow = not claim.cfg.Reclaim.BodyFollow
			end,
		},
		{
			text = function()
				return "alt rotation: " .. tostring(claim.cfg.AltRotation)
			end,
			run = function()
				claim.cfg.AltRotation = Util.cycle({ 0, 0.05, 0.5 }, claim.cfg.AltRotation)
			end,
		},
		{
			text = function()
				return "teleport test"
			end,
			run = function()
				driver:Teleport(cfg.Harness.TeleportDistance)
			end,
		},
		{
			text = function()
				return "reset stats"
			end,
			run = function()
				claim:ResetStats()
			end,
		},
		{
			text = function()
				return "restart start-up"
			end,
			run = function()
				bringUp(player.Character)
			end,
		},
		{
			text = function()
				return "stop"
			end,
			run = function()
				api.Stop()
			end,
		},
	}

	overlay = Overlay.new({
		maid = maid,
		claim = claim,
		actions = actions,
		version = cfg.Version,
		getBodyInfo = function()
			local lock = ""
			if camRig.Shiftlock then
				lock = "  [shift lock]"
			end
			return {
				mode = body.mode,
				state = body:GetState(),
				walk = body.walkSpeed,
				jump = body.jumpPower,
				hip = body.hipHeight,
				zoom = camRig.Zoom,
				lock = lock,
			}
		end,
	})

	----------------------------------------------------------------
	-- public api
	----------------------------------------------------------------
	function api.Stop()
		if not running then
			return
		end
		running = false
		pcall(function()
			claim:Destroy()
		end)
		maid:Clean()
		local ch = player.Character
		local hum = nil
		if ch then
			hum = ch:FindFirstChildOfClass("Humanoid")
		end
		local cam = Workspace.CurrentCamera
		if cam and hum then
			cam.CameraSubject = hum
		end
		if env.ExireReanimate == api then
			env.ExireReanimate = nil
		end
	end

	api.Config = cfg
	api.Claim = claim
	api.Body = body
	api.Camera = camRig
	api.Input = input
	api.Driver = driver
	env.ExireReanimate = api
	return api
end

return M
end

