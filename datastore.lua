__defs["core/saves"] = function(require)
-- core/saves.lua
-- Tiny JSON settings file (volume, mute, last mode, zoom, HUD visibility).
-- File access needs writefile/readfile; without them values still work for the
-- current session, they just are not persisted. Writes are debounced.

local Util = require("core/util")

local HttpService = game:GetService("HttpService")

local Caps = Util.Caps

local Saves = {}
Saves.__index = Saves

-- cfg = Config.Saves
function Saves.new(cfg)
	local self = setmetatable({}, Saves)
	self.cfg = cfg
	self.data = {}
	self.dirty = false
	self.idle = 0
	self.warned = false
	self.enabled = cfg.Enabled ~= false and Caps.writefile ~= nil and Caps.readfile ~= nil
	if self.enabled then
		self:_load()
	end
	return self
end

function Saves:_load()
	if Caps.isfile then
		local ok, exists = pcall(Caps.isfile, self.cfg.File)
		if not ok or not exists then
			return
		end
	end
	local ok, raw = pcall(Caps.readfile, self.cfg.File)
	if not ok or type(raw) ~= "string" or raw == "" then
		return
	end
	local ok2, decoded = pcall(function()
		return HttpService:JSONDecode(raw)
	end)
	if ok2 and type(decoded) == "table" then
		self.data = decoded
	end
end

function Saves:Get(key, default)
	local v = self.data[key]
	if v == nil then
		return default
	end
	return v
end

function Saves:Set(key, value)
	if self.data[key] ~= value then
		self.data[key] = value
		if self.enabled then
			self.dirty = true
			self.idle = 0
		end
	end
end

function Saves:Flush()
	if not self.enabled or not self.dirty then
		return
	end
	self.dirty = false
	local ok, json = pcall(function()
		return HttpService:JSONEncode(self.data)
	end)
	if not ok then
		return
	end
	local ok2, err = pcall(Caps.writefile, self.cfg.File, json)
	if not ok2 and not self.warned then
		self.warned = true
		warn("[Exire] could not write " .. tostring(self.cfg.File) .. ": " .. tostring(err))
	end
end

function Saves:Step(dt)
	if self.dirty then
		self.idle = self.idle + dt
		if self.idle >= (self.cfg.Debounce or 2) then
			self:Flush()
		end
	end
end

return Saves
end

