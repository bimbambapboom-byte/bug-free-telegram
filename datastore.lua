function Claim:_setMass(e, heavy)
	local h = e.Handle
	if not h then
		return
	end
	if heavy then
		h.Massless = false
		h.CustomPhysicalProperties = nil
	else
		h.Massless = true
		h.CustomPhysicalProperties = PhysicalProperties.new(self.cfg.MasslessDensity, 0, 0, 0, 0)
	end
end

-- Velocity used right after (re)claiming: aim the hat back at the body.
function Claim:_burstVelocity(pos)
	local cfg = self.cfg
	local net = cfg.Netless.Base
	local up = Vector3.new(0, net, 0)
	if cfg.BurstMode == "none" then
		return Vector3.zero
	end
	local getBodyPos = self.deps.getBodyPos
	if cfg.BurstMode == "up" or not getBodyPos then
		return up
	end
	local body = getBodyPos()
	if not body then
		return up
	end
	local off = body - pos
	local g = Workspace.Gravity
	local a = net * net - 2 * g * off.Y
	local t = (net * 1.2) / g
	if a > 0 then
		t = (net + math.sqrt(a)) / g
	end
	return up + Vector3.new(off.X, 0, off.Z) / t
end

function Claim:_align(e, index, count, dt, now)
	local provider = self.provider
	if not provider then
		return
	end
	local h = e.Handle
	local cfg = self.cfg
	local targetCF, targetVel = provider(e, index, count, now)
	if not targetCF then
		return
	end
	targetVel = targetVel or Vector3.zero

	-- never target below the destroy height
	local pos = targetCF.Position
	if cfg.VoidClamp then
		local limit = self.fpdh + cfg.VoidMargin
		if pos.Y < limit then
			targetCF = targetCF + Vector3.new(0, limit - pos.Y, 0)
			pos = targetCF.Position
		end
	end

	-- movement velocity of the path actually taken (chase when the target jumps)
	local last = e.LastPos
	local vel = Vector3.zero
	if last and dt > 0 then
		vel = (pos - last) / dt
	end
	local mag = vel.Magnitude
	e.Capped = false
	if last and mag > cfg.SpeedCap then
		vel = vel.Unit * cfg.SpeedCap
		pos = last + vel * dt
		targetCF = targetCF.Rotation + pos
		mag = cfg.SpeedCap
		e.Capped = true
	end
	e.LastPos = pos

	local rv = Vector3.new(math.sin(now * 14), math.sin(now * 15 + 1.0472), math.sin(now * 16 + 2.0944))
	if mag < cfg.IdleSpeed then
		targetCF = targetCF + rv * cfg.IdleJitter
	end
	if cfg.AltRotation ~= 0 then
		e.AltSign = -e.AltSign
		targetCF = targetCF * CFrame.Angles(0, 0, math.rad(cfg.AltRotation) * e.AltSign)
	end

	-- velocity written to the handle
	local ctx = self._ctx
	ctx.t = now
	ctx.dt = dt
	ctx.age = now - e.ClaimStart
	local nv
	if e.State == "Claiming" and ctx.age < cfg.BurstTime then
		nv = self:_burstVelocity(pos)
	else
		local src = targetVel
		if src.Magnitude <= 0.01 then
			src = vel
		end
		nv = self.netlessFn(src, ctx, cfg.Netless)
	end

	if h.CanCollide then
		h.CanCollide = false
	end
	local getLTM = self.deps.getLTM
	if getLTM then
		local ltm = getLTM()
		if h.LocalTransparencyModifier ~= ltm then
			h.LocalTransparencyModifier = ltm
		end
	end
	h.AssemblyLinearVelocity = nv
	h.CFrame = targetCF
	if cfg.UseAngularVelocity and e.LastCF and dt > 0 then
		local rel = e.LastCF:ToObjectSpace(targetCF)
		local axis, angle = rel:ToAxisAngle()
		h.AssemblyAngularVelocity = e.LastCF:VectorToWorldSpace(axis * angle) / dt + rv * cfg.IdleJitter
	else
		h.AssemblyAngularVelocity = rv
	end
	e.LastCF = targetCF
end

function Claim:_stepEntry(e, index, count, dt, now)
	local h = e.Handle
	if not h then
		return
	end
	if not h:IsDescendantOf(Workspace) then
		if e.State ~= "Gone" then
			self:_log("gone " .. e.Name)
		end
		e.State = "Gone"
		e.Handle = nil
		e.Accessory = nil
		e.GoneSince = now
		return
	end
	if h.Anchored then
		e.State = "Blocked"
		e.LastPos = h.Position
		return
	end
	if #h:GetJoints() > 0 then
		e.State = "Attached"
		e.LastPos = h.Position
		return
	end

	local cfg = self.cfg
	local owned = self:_isOwner(h)
	local st = e.State
	if owned then
		if st ~= "Claiming" and st ~= "Owned" then
			local dur = now - (e.UnownedSince or now)
			if e.WasOwned then
				e.Reowns = e.Reowns + 1
				e.ReownSum = e.ReownSum + dur
				self.stats.reowns = self.stats.reowns + 1
				self.stats.reownSum = self.stats.reownSum + dur
				self:_log(string.format("reown %s after %.2fs", e.Name, dur))
			else
				self.stats.claims = self.stats.claims + 1
				self.stats.claimSum = self.stats.claimSum + dur
				self:_log(string.format("claimed %s in %.2fs", e.Name, dur))
			end
			e.WasOwned = true
			e.State = "Claiming"
			e.ClaimStart = now
			e.UnownedSince = nil
			self:_setMass(e, true)
		elseif st == "Claiming" and (now - e.ClaimStart) >= cfg.HeavyPhase then
			e.State = "Owned"
			self:_setMass(e, false)
		end
		self:_align(e, index, count, dt, now)
	else
		if st == "Claiming" or st == "Owned" then
			e.Drops = e.Drops + 1
			self.stats.drops = self.stats.drops + 1
			e.UnownedSince = now
			self:_log("DROP " .. e.Name)
		elseif st ~= "Unowned" then
			e.UnownedSince = now
		end
		e.State = "Unowned"
		e.LastPos = h.Position
	end

	-- ownership percentage over roughly the last 10 seconds
	local alpha = 1 - math.exp(-dt / 10)
	local sample = 0
	if owned then
		sample = 1
	end
	if e.Ema == nil then
		e.Ema = sample
	else
		e.Ema = e.Ema + (sample - e.Ema) * alpha
	end
end

function Claim:_endStage2(ok)
	local s = self.stage2
	if s.entry and ok then
		self.stats.stage2ok = self.stats.stage2ok + 1
		self:_log(string.format("stage2 recovered %s (%d frames)", s.entry.Name, s.frames))
	end
	s.entry = nil
	s.frames = 0
end

-- Stage 2: park the real root part on a hat we do not own, so the engine
-- sees our character right next to it and can hand ownership back.
function Claim:_stepReclaim(now)
	local rc = self.cfg.Reclaim
	local s = self.stage2
	local root = nil
	local getRoot = self.deps.getRoot
	if getRoot then
		root = getRoot()
		if root and not root.Parent then
			root = nil
		end
	end

	if not rc.Stage2 then
		if s.entry then
			self:_endStage2(false)
		end
	else
		local cand = nil
		if s.entry and s.entry.Handle and s.entry.State == "Unowned" then
			cand = s.entry
		else
			if s.entry then
				self:_endStage2(s.entry.State == "Claiming" or s.entry.State == "Owned")
			end
			if now >= s.cooldownUntil then
				for i = 1, #self.entries do
					local e = self.entries[i]
					if e.State == "Unowned" and e.Handle and e.UnownedSince and (now - e.UnownedSince) >= rc.LostGrace then
						local v = e.Handle.AssemblyLinearVelocity
						if math.abs(v.X) < rc.LostMaxVelXZ and math.abs(v.Y) < rc.LostMaxVelY and math.abs(v.Z) < rc.LostMaxVelXZ then
							cand = e
							break
						end
					end
				end
			end
		end
		if cand and root and self:_isOwner(root) then
			if s.entry ~= cand then
				s.entry = cand
				s.frames = 0
				self.stats.stage2 = self.stats.stage2 + 1
				self:_log("stage2 -> " .. cand.Name)
			end
			s.frames = s.frames + 1
			if s.frames > rc.MaxFramesPerAttempt then
				self:_log("stage2 gave up on " .. cand.Name)
				s.entry = nil
				s.frames = 0
				s.cooldownUntil = now + rc.Cooldown
			else
				root.CFrame = cand.Handle.CFrame
				root.AssemblyLinearVelocity = Vector3.zero
				return
			end
		end
	end

	if rc.BodyFollow and root and self.deps.getFollowCF and self:_isOwner(root) then
		root.CFrame = self.deps.getFollowCF()
		root.AssemblyLinearVelocity = Vector3.zero
	end
end

function Claim:_cleanup(now)
	local list = self.entries
	for i = #list, 1, -1 do
		local e = list[i]
		if e.State == "Gone" and e.GoneSince and (now - e.GoneSince) > 60 then
			table.remove(list, i)
		end
	end
end

function Claim:Step(dt)
	if not self.enabled then
		return
	end
	local now = os.clock()
	self:_applySimRadius()
	if self._nanSet and now >= self._nextNan then
		self._nextNan = now + 1
		local v = Workspace.FallenPartsDestroyHeight
		if v == v then
			pcall(function()
				Workspace.FallenPartsDestroyHeight = 0 / 0
			end)
		end
	end
	local count = #self.entries
	for i = 1, count do
		self:_stepEntry(self.entries[i], i, count, dt, now)
	end
	self:_stepReclaim(now)
	self:_cleanup(now)
end

----------------------------------------------------------------------
-- reporting
----------------------------------------------------------------------
function Claim:Summary()
	local hats, owned, emaSum, emaN = 0, 0, 0, 0
	for i = 1, #self.entries do
		local e = self.entries[i]
		if e.Handle and (e.State == "Owned" or e.State == "Claiming" or e.State == "Unowned") then
			hats = hats + 1
			if e.State ~= "Unowned" then
				owned = owned + 1
			end
			if e.Ema then
				emaSum = emaSum + e.Ema
				emaN = emaN + 1
			end
		end
	end
	local st = self.stats
	local own = 0
	if emaN > 0 then
		own = emaSum / emaN
	end
	local reownAvg = 0
	if st.reowns > 0 then
		reownAvg = st.reownSum / st.reowns
	end
	local claimAvg = 0
	if st.claims > 0 then
		claimAvg = st.claimSum / st.claims
	end
	return {
		hats = hats,
		owned = owned,
		own = own,
		drops = st.drops,
		reowns = st.reowns,
		reownAvg = reownAvg,
		claims = st.claims,
		claimAvg = claimAvg,
		stage2 = st.stage2,
		stage2ok = st.stage2ok,
		simMethod = self.simMethod,
	}
end

function Claim:ResetStats()
	self.stats = { drops = 0, reowns = 0, reownSum = 0, claims = 0, claimSum = 0, stage2 = 0, stage2ok = 0 }
	for i = 1, #self.entries do
		local e = self.entries[i]
		e.Drops = 0
		e.Reowns = 0
		e.ReownSum = 0
		e.Ema = nil
	end
	self:_log("stats reset")
end

function Claim:Destroy()
	self.enabled = false
	if self._charMaid then
		self._charMaid:Clean()
	end
	for i = 1, #self.entries do
		local h = self.entries[i].Handle
		if h and h.Parent then
			pcall(function()
				h.Massless = false
				h.CustomPhysicalProperties = nil
			end)
		end
	end
	if self._nanSet then
		pcall(function()
			Workspace.FallenPartsDestroyHeight = self._fpdhOriginal
		end)
	end
	self.events:DisconnectAll()
end

return Claim
end

__defs["claim/netless"] = function(require)
-- claim/netless.lua
-- Pluggable "netless" velocity functions. Each one decides what velocity is
-- written to a hat handle every frame while we own it. They are deliberately
-- separate so the harness can A/B them against each other.
--
-- fn(vel, ctx, cfg) -> Vector3
--   vel : velocity of the target point (studs/s)
--   ctx : { t = os.clock(), dt = frame delta, age = seconds since claim }
--   cfg : Config.Claim.Netless

local Netless = {}
Netless.Variants = {}
Netless.Order = { "patchma", "myworld", "wobble", "none" }

local V3 = Vector3.new

-- Patchma-style: horizontal velocity x10 (or capped direction when fast) plus
-- a constant upward Y.
Netless.Variants.patchma = function(vel, ctx, cfg)
	local up = V3(0, cfg.Base, 0)
	if vel.Magnitude > cfg.Base then
		local d = vel.Unit
		return V3(d.X * cfg.XZCap, 0, d.Z * cfg.XZCap) + up
	end
	return V3(vel.X * cfg.XZMul, 0, vel.Z * cfg.XZMul) + up
end

-- MyWorld's older formula, kept as a reference variant.
Netless.Variants.myworld = function(vel, ctx, cfg)
	if vel.Magnitude > 1 then
		local u = vel.Unit
		if u.Y > 0.25 or u.Y < -0.75 then
			return u * (25.1 / u.Y)
		end
	end
	return V3(0, 25.1, 0) + V3(vel.X * 8, 0, vel.Z * 8)
end

-- Uhhhhhh-style: Y wobbles slowly between Base and Base + Wobble, horizontal
-- part is clamped to that magnitude before the multiplier.
Netless.Variants.wobble = function(vel, ctx, cfg)
	local net = cfg.Base + ((math.sin(ctx.t * 0.5) + 1) / 2) * cfg.Wobble
	local h = V3(vel.X, 0, vel.Z)
	if h.Magnitude > net then
		h = h.Unit * net
	end
	return V3(h.X * cfg.XZMul, net, h.Z * cfg.XZMul)
end

-- Negative control: no netless velocity at all.
Netless.Variants.none = function(vel, ctx, cfg)
	return Vector3.zero
end

function Netless.nextName(name)
	for i = 1, #Netless.Order do
		if Netless.Order[i] == name then
			return Netless.Order[(i % #Netless.Order) + 1]
		end
	end
	return Netless.Order[1]
end

return Netless
end

__defs["claim/start"] = function(require)
-- claim/start.lua
-- Start-up strategies: get the real character's hats loose (unwelded) so the
-- claim system can take them. Strategies are tried in cfg.Start.Order and the
-- first one that verifiably frees every tracked hat wins.

local Util = require("core/util")

local Caps = Util.Caps
local Workspace = game:GetService("Workspace")

local Start = {}

local strategies = {}

-- ask the server to break the joints (needs replicatesignal), then kill locally
strategies.server = {
	available = function()
		return Caps.replicatesignal ~= nil
	end,
	run = function(char, hum)
		pcall(function()
			Caps.replicatesignal(hum.ServerBreakJoints)
		end)
		pcall(function()
			hum.BreakJointsOnDeath = true
		end)
		pcall(function()
			hum.Health = 0
		end)
		pcall(function()
			hum:ChangeState(Enum.HumanoidStateType.Dead)
		end)
	end,
}

-- plain client-side BreakJoints + Health = 0
strategies.client = {
	available = function()
		return true
	end,
	run = function(char, hum)
		pcall(function()
			char:BreakJoints()
		end)
		pcall(function()
			hum.Health = 0
		end)
	end,
}

local function disableCharScripts(char)
	for _, d in ipairs(char:GetDescendants()) do
		if d:IsA("LocalScript") then
			pcall(function()
				d.Enabled = false
			end)
			pcall(function()
				d.Disabled = true
			end)
		end
	end
end

-- true when every live handle has no joints left (and at least one exists)
local function allFree(handles)
	local live = 0
	for _, h in ipairs(handles) do
		if h.Parent and h:IsDescendantOf(Workspace) then
			live = live + 1
			if #h:GetJoints() > 0 then
				return false
			end
		end
	end
	return live > 0
end

-- ctx = { char, cfg (Config.Start), getHandles, log, isAlive }
function Start.run(ctx)
	local char = ctx.char
	local hum = char:FindFirstChildOfClass("Humanoid")
	if not hum then
		ctx.log("start: no humanoid")
		return false
	end
	if ctx.cfg.DisableCharScripts then
		disableCharScripts(char)
	end
	if #ctx.getHandles() == 0 then
		ctx.log("start: no hats found on this character")
		return false
	end
	for _, name in ipairs(ctx.cfg.Order) do
		local s = strategies[name]
		if s and s.available() then
			ctx.log("start: trying '" .. name .. "'")
			s.run(char, hum)
			local deadline = os.clock() + ctx.cfg.Timeout
			while os.clock() < deadline do
				if not ctx.isAlive() then
					return false
				end
				if allFree(ctx.getHandles()) then
					ctx.log("start: hats free via '" .. name .. "'")
					return true, name
				end
				task.wait()
			end
			ctx.log("start: '" .. name .. "' timed out")
		else
			ctx.log("start: '" .. tostring(name) .. "' unavailable")
		end
	end
	ctx.log("start: FAILED to free the hats")
	return false
end

return Start
end

