----------------------------------------------------------------------
-- helpers
----------------------------------------------------------------------
function Util.randomString(len)
	len = len or math.random(8, 15)
	local chars = {}
	for i = 1, len do
		if math.random(2) == 1 then
			chars[i] = string.char(math.random(65, 90))
		else
			chars[i] = string.char(math.random(97, 122))
		end
	end
	return table.concat(chars)
end

-- returns the element after `current` in `list` (wraps around)
function Util.cycle(list, current)
	for i = 1, #list do
		if list[i] == current then
			return list[(i % #list) + 1]
		end
	end
	return list[1]
end

----------------------------------------------------------------------
-- Maid: collect things to clean up with one call
----------------------------------------------------------------------
local Maid = {}
Maid.__index = Maid

function Maid.new()
	return setmetatable({ _items = {} }, Maid)
end

function Maid:Give(item)
	if item ~= nil then
		self._items[#self._items + 1] = item
	end
	return item
end

local function cleanItem(item)
	local kind = typeof(item)
	if kind == "RBXScriptConnection" then
		item:Disconnect()
	elseif kind == "Instance" then
		item:Destroy()
	elseif kind == "function" then
		item()
	elseif kind == "thread" then
		task.cancel(item)
	elseif kind == "table" then
		if type(item.Disconnect) == "function" then
			item:Disconnect()
		elseif type(item.Destroy) == "function" then
			item:Destroy()
		elseif type(item.Clean) == "function" then
			item:Clean()
		end
	end
end

function Maid:Clean()
	local items = self._items
	self._items = {}
	for i = #items, 1, -1 do
		local ok, err = pcall(cleanItem, items[i])
		if not ok then
			warn("[Exire] cleanup error: " .. tostring(err))
		end
	end
end

Maid.Destroy = Maid.Clean
Util.Maid = Maid

----------------------------------------------------------------------
-- Signal: tiny synchronous event
----------------------------------------------------------------------
local Signal = {}
Signal.__index = Signal

function Signal.new()
	return setmetatable({ _list = {} }, Signal)
end

function Signal:Connect(fn)
	local list = self._list
	local conn = { Connected = true, Fn = fn }
	function conn.Disconnect(c)
		if not c.Connected then
			return
		end
		c.Connected = false
		for i = 1, #list do
			if list[i] == c then
				table.remove(list, i)
				break
			end
		end
	end
	list[#list + 1] = conn
	return conn
end

function Signal:Fire(...)
	local snapshot = table.clone(self._list)
	for i = 1, #snapshot do
		local conn = snapshot[i]
		if conn.Connected then
			local ok, err = pcall(conn.Fn, ...)
			if not ok then
				warn("[Exire] signal handler error: " .. tostring(err))
			end
		end
	end
end

function Signal:DisconnectAll()
	local snapshot = table.clone(self._list)
	for i = 1, #snapshot do
		snapshot[i]:Disconnect()
	end
end

Util.Signal = Signal

return Util
end

__defs["harness/driver"] = function(require)
-- harness/driver.lua
-- Test driver: a client-only anchor part that you fly around with WASD, and a
-- set of formations that give every hat a target relative to that anchor.
-- This stands in for the real body/skeleton until that exists, so the claim
-- system can be measured on its own.

local Util = require("core/util")

local UserInputService = game:GetService("UserInputService")
local Workspace = game:GetService("Workspace")

