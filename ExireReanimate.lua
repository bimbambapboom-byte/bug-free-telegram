__defs["init"] = function(require)
-- init.lua
-- Wires config, claim core, start-up strategies and the test harness together.

local Util = require("core/util")
local Config = require("core/config")
local Claim = require("claim/claim")
local Start = require("claim/start")
local Netless = require("claim/netless")
local Driver = require("harness/driver")
local Overlay = require("harness/overlay")

local Players = game:GetService("Players")
local RunService = game:GetService("RunService")
local Workspace = game:GetService("Workspace")

local M = {}

function M.start(userCfg)
	local env = Util.getEnv()
	local previous = env.ExireReanimate
	if previous and type(previous.Stop) == "function" then
		pcall(previous.Stop)
	end

	local cfg = Config.build(userCfg)
	local maid = Util.Maid.new()
	local player = Players.LocalPlayer
	local running = true
	local api = {}

	local function getRoot()
		local ch = player.Character
		if ch then
			return ch:FindFirstChild("HumanoidRootPart")
		end
		return nil
	end

	-- where the test anchor starts: on top of the real character if there is one
	local startCF = CFrame.new(0, 10, 0)
	local root = getRoot()
	if root then
		startCF = root.CFrame
	elseif Workspace.CurrentCamera then
		startCF = CFrame.new(Workspace.CurrentCamera.Focus.Position)
	end

	local driver = Driver.new(cfg.Harness, maid, startCF)
	local claim = Claim.new(cfg, {
		getRoot = getRoot,
		getBodyPos = function()
			local r = getRoot()
			if r then
				return r.Position
			end
			return nil
		end,
		getFollowCF = function()
			return driver.CF
		end,
	})
	claim:SetProvider(driver:GetProvider())

	----------------------------------------------------------------
	-- character bring-up (initial character and every respawn)
	----------------------------------------------------------------
	local token = 0
	local function bringUp(char)
		if not char then
			return
		end
		token = token + 1
		local myToken = token
		task.spawn(function()
			local hum = char:WaitForChild("Humanoid", 10)
			if not hum then
				return
			end
			task.wait(cfg.Start.ScanDelay)
			if not running or myToken ~= token then
				return
			end
			claim:Track(char)
			-- wait for the accessory list to settle
			local previousCount = -1
			for _ = 1, 15 do
				local n = #claim:GetHandles()
				if n > 0 and n == previousCount then
					break
				end
				previousCount = n
				task.wait(0.2)
			end
			if not running or myToken ~= token then
				return
			end
			Start.run({
				char = char,
				cfg = cfg.Start,
				getHandles = function()
					return claim:GetHandles()
				end,
				log = function(msg)
					claim:_log(msg)
				end,
				isAlive = function()
					return running and myToken == token and char.Parent ~= nil
				end,
			})
		end)
	end

	maid:Give(player.CharacterAdded:Connect(function(char)
		if cfg.Start.AutoRestartOnRespawn then
			bringUp(char)
		end
	end))
	if cfg.Start.AutoRun and player.Character then
		bringUp(player.Character)
	end

	----------------------------------------------------------------
	-- frame loops
	----------------------------------------------------------------
	maid:Give(RunService.Heartbeat:Connect(function(dt)
		driver:Step(dt)
		claim:Step(dt)
	end))
	maid:Give(RunService.RenderStepped:Connect(function()
		driver:EnforceCamera()
	end))

	----------------------------------------------------------------
	-- overlay actions
	----------------------------------------------------------------
	local function onOff(v)
		if v then
			return "on"
		end
		return "off"
	end

	local actions = {
		{
			text = function()
				return "netless: " .. claim.variant
			end,
			run = function()
				claim:SetVariant(Netless.nextName(claim.variant))
			end,
		},
		{
			text = function()
				return "formation: " .. driver.formationName
			end,
			run = function()
				driver:CycleFormation()
			end,
		},
		{
			text = function()
				return "heavy phase: " .. tostring(claim.cfg.HeavyPhase) .. "s"
			end,
			run = function()
				claim.cfg.HeavyPhase = Util.cycle({ 0, 2, 5.67 }, claim.cfg.HeavyPhase)
			end,
		},
		{
			text = function()
				return "burst: " .. claim.cfg.BurstMode
			end,
			run = function()
				claim.cfg.BurstMode = Util.cycle({ "ballistic", "up", "none" }, claim.cfg.BurstMode)
			end,
		},
		{
			text = function()
				return "reclaim stage2: " .. onOff(claim.cfg.Reclaim.Stage2)
			end,
			run = function()
				claim.cfg.Reclaim.Stage2 = not claim.cfg.Reclaim.Stage2
			end,
		},
		{
			text = function()
				return "body follow: " .. onOff(claim.cfg.Reclaim.BodyFollow)
			end,
			run = function()
				claim.cfg.Reclaim.BodyFollow = not claim.cfg.Reclaim.BodyFollow
			end,
		},
		{
			text = function()
				return "alt rotation: " .. tostring(claim.cfg.AltRotation)
			end,
			run = function()
				claim.cfg.AltRotation = Util.cycle({ 0, 0.05, 0.5 }, claim.cfg.AltRotation)
			end,
		},
		{
			text = function()
				return "teleport test"
			end,
			run = function()
				driver:Teleport(cfg.Harness.TeleportDistance)
			end,
		},
		{
			text = function()
				return "reset stats"
			end,
			run = function()
				claim:ResetStats()
			end,
		},
		{
			text = function()
				return "restart start-up"
			end,
			run = function()
				bringUp(player.Character)
			end,
		},
		{
			text = function()
				return "stop"
			end,
			run = function()
				api.Stop()
			end,
		},
	}

	Overlay.new({
		maid = maid,
		claim = claim,
		driver = driver,
		actions = actions,
		version = cfg.Version,
	})

	----------------------------------------------------------------
	-- public api
	----------------------------------------------------------------
	function api.Stop()
		if not running then
			return
		end
		running = false
		pcall(function()
			claim:Destroy()
		end)
		maid:Clean()
		local ch = player.Character
		local hum = nil
		if ch then
			hum = ch:FindFirstChildOfClass("Humanoid")
		end
		local cam = Workspace.CurrentCamera
		if cam and hum then
			cam.CameraSubject = hum
		end
		if env.ExireReanimate == api then
			env.ExireReanimate = nil
		end
	end

	api.Config = cfg
	api.Claim = claim
	api.Driver = driver
	env.ExireReanimate = api
	return api
end

return M
end

__defs["main"] = function(require)
-- main.lua : entry point of the bundle.
local Util = require("core/util")
local Exire = require("init")

local env = Util.getEnv()
return Exire.start(env.ExireConfig)
end

return __require("main")
