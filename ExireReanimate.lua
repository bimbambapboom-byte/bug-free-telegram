-- claim/claim.lua
-- Per-hat claim state machine, ownership metrics and reclaim logic.
--
-- Provider contract (Claim:SetProvider):
--   provider(entry, index, count, now) -> CFrame, Vector3
--   the CFrame the hat handle should be at, and the velocity of that target
--   point in studs/s (Vector3.zero is fine).
--
-- Entry states:
--   Attached  handle is still welded to something (cannot be claimed yet)
--   Unowned   detached, but someone else (or nobody) simulates it
--   Claiming  we own it; heavy phase + return-to-body burst
--   Owned     we own it; steady state
--   Blocked   anchored by someone else
--   Gone      handle destroyed / left workspace (kept so a respawn can re-bind)

local Util = require("core/util")
local Netless = require("claim/netless")

local Caps = Util.Caps
local Players = game:GetService("Players")
local Workspace = game:GetService("Workspace")

local Claim = {}
Claim.__index = Claim

